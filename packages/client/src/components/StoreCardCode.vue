<script setup lang="ts">
import { ref, useTemplateRef, watch } from 'vue';
import JsBarcode from 'jsbarcode';
import QRCode from 'qrcode';
import { useI18n } from 'vue-i18n';
import type { StoreCard } from '@/api/services/types/library';
import { formatCardNumber, JSBARCODE_FORMATS } from '@/utils/store-card';

const props = defineProps<{ card: StoreCard }>();

const { t } = useI18n();
const root = useTemplateRef('root');
const barcode = useTemplateRef('barcode');
const qrSvg = ref('');
const invalid = ref(false);

/** The colors from --app-code-dark/light: the libraries need them as values, not variables */
function colors(element: Element) {
    const style = getComputedStyle(element);
    return {
        dark: style.getPropertyValue('--app-code-dark').trim() || '#000000',
        light: style.getPropertyValue('--app-code-light').trim() || '#ffffff',
    };
}

async function render() {
    if (!root.value) return;
    const { dark, light } = colors(root.value);
    invalid.value = false;
    const { code, format } = props.card;
    if (format === 'qr') {
        qrSvg.value = await QRCode.toString(code, {
            type: 'svg',
            margin: 0,
            errorCorrectionLevel: 'M',
            color: { dark, light },
        });
    } else if (barcode.value) {
        JsBarcode(barcode.value, code, {
            format: JSBARCODE_FORMATS[format],
            displayValue: false,
            margin: 0,
            height: 110,
            width: 2.5,
            lineColor: dark,
            background: light,
            valid: (valid) => {
                invalid.value = !valid;
            },
        });
    }
}

watch(
    [() => props.card.code, () => props.card.format, root, barcode],
    () => void render().catch(() => (invalid.value = true)),
    { immediate: true },
);
</script>

<!-- A loyalty card as the till's scanner reads it: dark on light in both color schemes -->
<template>
    <figure ref="root" class="store-card-code">
        <p v-if="invalid" class="invalid">{{ t('cards.invalid') }}</p>
        <!-- eslint-disable-next-line vue/no-v-html -- SVG generated by the qrcode library -->
        <div v-else-if="card.format === 'qr'" class="qr" v-html="qrSvg" />
        <svg v-else ref="barcode" class="barcode" />
        <figcaption class="number">{{ formatCardNumber(card.code) }}</figcaption>
    </figure>
</template>

